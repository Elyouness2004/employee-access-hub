-- Notification Center (Enterprise Notification Center): one employee's history of
-- notifications raised automatically by business events. Additive and backward
-- compatible: a single CREATE TABLE + indexes, no change to any existing table.
-- Append-only in spirit like audit_log / security_event (BR-06): rows are inserted
-- and only ever transition read/unread — content is never updated, never deleted;
-- accordingly (and like the other history tables) there is no foreign key.
-- Must run on PostgreSQL (compose) AND H2 in PostgreSQL mode (local/tests): common
-- SQL subset only; the id is generated by the application (@UuidGenerator).
create table notification (
    id             uuid         primary key,
    -- owner: the Keycloak subject the notification is addressed to (JWT `sub`),
    -- the same key the self-service session surface scopes ownership on
    recipient_id   uuid         not null,
    -- the hr employee record the recipient maps to, when known (traceability only);
    -- null for cross-context events whose aggregate is not an hr employee id
    employee_id    uuid,
    type           varchar(40)  not null,
    status         varchar(10)  not null,
    title          varchar(150) not null,
    message        varchar(500) not null,
    correlation_id varchar(64),
    created_at     timestamp with time zone not null,
    read_at        timestamp with time zone,
    constraint ck_notification_status check (status in ('UNREAD', 'READ'))
);

-- Default query: a recipient's notifications, newest first (history, latest, single).
create index ix_notification_recipient on notification (recipient_id, created_at);
-- Unread list and unread count for one recipient.
create index ix_notification_recipient_status on notification (recipient_id, status);
